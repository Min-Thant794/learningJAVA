package oneDArray;

public class OneDArray2 {
    public static void main(String[] args)
    {
        double[] arr = new double[2];

        arr[1] = 1.1;

        System.out.println("The Value of arr[0] is: " + arr[0]);
        System.out.println("The Value of arr[1] is: " + arr[1]);
        System.out.println("The Size of arr is: " + arr.length);
    }
}